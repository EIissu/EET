"""
Generate the raw API-shaped Xbox fixtures for Career Stats Shared/fixtures/xbox.

These mimic what achievements.xboxlive.com, titlehub.xboxlive.com and
profile.xboxlive.com actually return, so that loading them exercises the real
mapping code in AchievementMapper rather than a shortcut.

Deterministic: seeded RNG, fixed reference date. Re-running produces byte-identical
output, so a fixture diff always means someone changed the generator on purpose.
"""

import json
import random
from datetime import datetime, timedelta, timezone

SEED = 20260904
random.seed(SEED)

