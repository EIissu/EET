def write(path, doc):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(doc, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    print("wrote", path)


def main():
    import os

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)))
    halo, unlock_by_index, catalogue = build_halo_achievements()
    titlehub = build_titlehub(halo)

    write(os.path.join(out, "achievements-halo-infinite.json"), halo)
    write(os.path.join(out, "achievements-recent.json"), build_recent(halo, unlock_by_index, catalogue))
    write(os.path.join(out, "titlehub-titlehistory.json"), titlehub)
    write(os.path.join(out, "profile-settings.json"), build_profile(titlehub))

    unlocked = [e for e in halo["achievements"] if e["progressState"] == "Achieved"]
    days = sorted({e["progression"]["timeUnlocked"][:10] for e in unlocked})
    print(
        "halo: %d achievements, %d unlocked, %d distinct unlock days, %s..%s"
        % (len(halo["achievements"]), len(unlocked), len(days), days[0], days[-1])
    )


if __name__ == "__main__":
    main()
