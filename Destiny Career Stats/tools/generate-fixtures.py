def value(stat_id: str, raw: float, display: str | None = None) -> dict:
    """One DestinyHistoricalStatsValue, in Bungie's shape."""
    if display is None:
        display = f"{raw:.0f}" if float(raw).is_integer() else f"{raw:.2f}"
    return {"statId": stat_id, "basic": {"value": raw, "displayValue": display}}


def envelope(response, note: str = NOTE) -> dict:
    return {
        "_note": note,
        "Response": response,
        "ErrorCode": 1,
        "ThrottleSeconds": 0,
        "ErrorStatus": "Success",
        "Message": "Ok",
        "MessageData": {},
    }


def write(name: str, payload) -> None:
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, indent=1, ensure_ascii=False)
        handle.write("\n")
    print(f"wrote {path} ({os.path.getsize(path)} bytes)")


def skill(t: float) -> float:
    """K/D skill curve across the window. t runs 0 (oldest) to 1 (newest)."""
    # A slightly S-shaped climb rather than a straight line, so the fitted slope is real
    # but the smoothed line still has something to do.
    return 0.90 + 0.50 * (0.35 * t + 0.65 * (1 / (1 + math.exp(-6 * (t - 0.45)))))


def win_chance(t: float) -> float:
    return 0.42 + 0.16 * t


def build_matches(rng: random.Random) -> list[dict]:
    """Lay ~120 matches over ~90 days in believable sessions."""
    play_days = sorted(rng.sample(range(DAYS), 46))
    sessions: list[tuple[int, int]] = []
    remaining = MATCH_TARGET
    for index, day in enumerate(play_days):
        left = len(play_days) - index
        count = max(1, min(6, round(remaining / left + rng.uniform(-1.2, 1.4))))
        count = min(count, remaining - (left - 1)) if left > 1 else remaining
        count = max(1, count)
        sessions.append((day, count))
        remaining -= count
        if remaining <= 0:
            break

    matches: list[dict] = []
    instance = 12000000000
    mode_pool = [m for m, w in MODE_WEIGHTS for _ in range(w)]

    for day, count in sessions:
        t = day / (DAYS - 1)
        # A session tends to stay in one activity type, the way people actually play.
        session_mode = rng.choice(mode_pool)
        start = END - timedelta(days=DAYS - 1 - day) - timedelta(hours=rng.uniform(0, 6))

        for slot in range(count):
            mode = session_mode if rng.random() < 0.72 else rng.choice(mode_pool)
            category = MODES[mode][1]
            candidates = [h for h, a in ACTIVITIES.items() if a[1] == mode]
            reference = rng.choice(candidates)

            instance += rng.randint(3, 97)
            period = start + timedelta(minutes=slot * rng.uniform(11, 26))

            # A session's own form wanders around the long-run trend.
            form = rng.gauss(0, 0.22)
            base = max(0.25, skill(t) + form)

            if category in (2, 3):
                duration = int(rng.uniform(430, 760)) if mode != 84 else int(rng.uniform(240, 520))
                deaths = max(0, int(round(rng.gauss(9.5, 3.0))))
                if mode == 84:
                    deaths = max(0, int(round(rng.gauss(2.4, 1.4))))
                kills = max(0, int(round(deaths * base + rng.gauss(0.6, 1.6))))
                if deaths == 0:
                    kills = max(kills, int(round(rng.uniform(4, 14))))
                assists = max(0, int(round(kills * rng.uniform(0.25, 0.65))))
                won = rng.random() < win_chance(t) + (0.10 if base > skill(t) else -0.06)
                standing = 0 if won else 1
                score = int(round(kills * rng.uniform(90, 135) + assists * 25))
                team_score = rng.choice([100, 90, 75]) if won else rng.randint(45, 89)
                players = 12 if mode in (10, 12, 43) else (6 if mode in (37, 48) else 6)
                if mode == 84:
                    players = 6
                if mode == 63:
                    players = 8
            else:
                duration = int(rng.uniform(900, 2600))
                deaths = max(0, int(round(rng.gauss(2.2, 1.9))))
                kills = int(round(rng.uniform(55, 190) * (0.8 + 0.4 * base)))
                assists = int(round(kills * rng.uniform(0.05, 0.2)))
                standing = None
                score = 0
                team_score = 0
                players = 3 if mode in (3, 46) else 6

            opponents = kills + assists
            efficiency = (kills + assists) / deaths if deaths else float(kills + assists)
            kd = kills / deaths if deaths else float(kills)
            kda = (kills + assists / 2) / deaths if deaths else float(kills + assists / 2)

            values = {
                "assists": value("assists", assists),
                "completed": value("completed", 1, "Yes"),
                "deaths": value("deaths", deaths),
                "kills": value("kills", kills),
                "opponentsDefeated": value("opponentsDefeated", opponents),
                "efficiency": value("efficiency", round(efficiency, 4), f"{efficiency:.2f}"),
                "killsDeathsRatio": value("killsDeathsRatio", round(kd, 4), f"{kd:.2f}"),
                "killsDeathsAssists": value("killsDeathsAssists", round(kda, 4), f"{kda:.2f}"),
                "activityDurationSeconds": value(
                    "activityDurationSeconds", duration, f"{duration // 60}m {duration % 60}s"
                ),
                "completionReason": value("completionReason", 0, "Objective Completed"),
                "fireteamId": value("fireteamId", 0),
                "startSeconds": value("startSeconds", 0),
                "timePlayedSeconds": value(
                    "timePlayedSeconds", duration, f"{duration // 60}m {duration % 60}s"
                ),
                "playerCount": value("playerCount", players),
                "teamScore": value("teamScore", team_score),
                "score": value("score", score),
            }
            if standing is not None:
                values["standing"] = value(
                    "standing", standing, "Victory" if standing == 0 else "Defeat"
                )

            matches.append(
                {
                    "character": rng.choice(CHARACTERS),
                    "period": period.strftime("%Y-%m-%dT%H:%M:%SZ"),
                    "activityDetails": {
                        "referenceId": reference,
                        "directorActivityHash": PLAYLIST_HASHES.get(mode, reference),
                        "instanceId": str(instance),
                        "mode": mode,
                        "modes": sorted({5 if category == 2 else 7, mode}),
                        "isPrivate": False,
                        "membershipType": MEMBERSHIP_TYPE,
                    },
                    "values": values,
                }
            )

    matches.sort(key=lambda m: m["period"], reverse=True)
    return matches


def all_time(entered, won, kills, deaths, assists, seconds, precision):
    """An allTime block, with the stat ids Bungie actually publishes in the General group."""
    kd = kills / deaths if deaths else float(kills)
    kda = (kills + assists / 2) / deaths if deaths else float(kills)
    eff = (kills + assists) / deaths if deaths else float(kills)
    lost = max(0, entered - won)
    block = {
        "activitiesEntered": value("activitiesEntered", entered),
        "activitiesWon": value("activitiesWon", won),
        "assists": value("assists", assists),
        "kills": value("kills", kills),
        "deaths": value("deaths", deaths),
        "killsDeathsRatio": value("killsDeathsRatio", round(kd, 4), f"{kd:.2f}"),
        "killsDeathsAssists": value("killsDeathsAssists", round(kda, 4), f"{kda:.2f}"),
        "efficiency": value("efficiency", round(eff, 4), f"{eff:.2f}"),
        "precisionKills": value("precisionKills", precision),
        "secondsPlayed": value(
            "secondsPlayed", seconds, f"{seconds // 3600}h {(seconds % 3600) // 60}m"
        ),
        "averageLifespan": value("averageLifespan", 87.4, "1m 27s"),
        "longestKillSpree": value("longestKillSpree", 11),
        "bestSingleGameKills": value("bestSingleGameKills", 34),
        "suicides": value("suicides", 61),
        "score": value("score", entered * 1180),
    }
    if won:
        ratio = won / lost if lost else float(won)
        block["winLossRatio"] = value("winLossRatio", round(ratio, 4), f"{ratio:.2f}")
    return block


