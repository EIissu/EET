"""Generate the synthetic Bungie-shaped fixtures in Career Stats Shared/fixtures.

Everything this writes is invented. The shapes are Bungie's -- the platform envelope, the
values dictionaries, the manifest layout -- so that loading a fixture exercises the real
mapping code in Destiny.Client rather than a shortcut around it. The numbers are not
recorded from any player.

The generated career deliberately contains a true, findable trend: K/D climbs from roughly
0.90 to roughly 1.40 across the ninety days, and the win rate climbs with it. That is there
so the trend charts have something real to detect and so the significance test in Trends.cs
has a reason to say "improving" rather than "steady".

Run:  python Destiny Career Stats/tools/generate-fixtures.py
"""

