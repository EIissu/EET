    # ---- a summary, so a human can sanity check the trend ---------------------------
    competitive = [m for m in matches if "standing" in m["values"]]
    half = len(competitive) // 2
    newer = competitive[:half]
    older = competitive[half:]

    def kd(rows):
        kills = sum(r["values"]["kills"]["basic"]["value"] for r in rows)
        deaths = sum(r["values"]["deaths"]["basic"]["value"] for r in rows)
        return kills / deaths if deaths else float(kills)

    def wr(rows):
        wins = sum(
            1 for r in rows if r["values"]["standing"]["basic"]["value"] == 0
        )
        return wins / len(rows) if rows else 0.0

